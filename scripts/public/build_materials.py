NUM = re.compile(r"\d+(?:[.,]\d+)?")


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=repo, check=True, capture_output=True, text=True, encoding="utf-8"
    ).stdout


def clean_markdown(md: str) -> list[str]:
    """Paragraph and list-item texts of a markdown document, markup removed."""
    md = re.sub(r"\A---\n.*?\n---\n", "", md, flags=re.S)
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    blocks, current = [], []
    for line in md.splitlines():
        stripped = line.strip()
        item = re.match(r"^([-*+]|\d+[.)]|\([a-z0-9]+\))\s+", stripped)
        if not stripped or stripped.startswith(("#", "|", "```")) or item:
            if current:
                blocks.append(" ".join(current))
            current = [stripped[item.end() :]] if item else []
            continue
        current.append(stripped)
    if current:
        blocks.append(" ".join(current))
    out = []
    for block in blocks:
        block = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", block)
        block = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", block)
        block = re.sub(r"\[([^\]]+)\]\[[^\]]*\]", r"\1", block)
        block = re.sub(r"<[^>]+>", "", block)
        block = re.sub(r"[*_`]{1,3}", "", block)
        block = re.sub(r"\s+", " ", block).strip()
        if block:
            out.append(block)
    return out


def sentences(md: str, low=40, high=420) -> list[str]:
    out = []
    for block in clean_markdown(md):
        for s in re.split(r"(?<=[.!?;])\s+(?=[A-Z0-9(\"“])", block):
            s = s.strip()
            if low <= len(s) <= high and re.search(r"[a-z]{3}", s):
                out.append(s)
    return out


def unit(source: str, doc: str, text: str, locator: str, **extra) -> dict:
    return {
        "unit_id": unit_id(source, doc, text),
        "source_id": source,
        "doc_id": doc,
        "text": text,
        "language": "en",
        "locator": locator,
        "numbers": NUM.findall(text),
        **extra,
    }


