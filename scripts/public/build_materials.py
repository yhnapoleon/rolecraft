def site_policy() -> list[dict]:
    repo = RAW / "site-policy" / "repo"
    head = git(repo, "rev-parse", "HEAD").strip()
    units = []
    for path in SITE_POLICY_FILES:
        revisions = [
            line.split("|") for line in git(repo, "log", "--format=%H|%cI", "--", path).splitlines()
        ][::-1]
        current = sentences((repo / path).read_text(encoding="utf-8"))
        url = f"https://github.com/github/site-policy/blob/{head}/{path}"
        seen = set()
        for index, text in enumerate(current):
            if text in seen:
                continue
            seen.add(text)
            units.append(
                unit(
                    "site-policy",
                    path,
                    text,
                    f"{path}@{head[:10]}#s{index}",
                    url=url,
                    revision=head,
                    revision_date=revisions[-1][1],
                    current=True,
                )
            )
        current_set = set(current)
        superseded = {}
        texts = {}
        for commit, _ in revisions:
            try:
                texts[commit] = sentences(git(repo, "show", f"{commit}:{path}"))
            except subprocess.CalledProcessError:
                texts[commit] = []
        for (old_c, old_d), (new_c, new_d) in zip(revisions, revisions[1:], strict=False):
            old, new = texts[old_c], texts[new_c]
            matcher = difflib.SequenceMatcher(None, old, new, autojunk=False)
            for tag, i1, i2, j1, j2 in matcher.get_opcodes():
                if tag != "replace" or i2 - i1 != j2 - j1:
                    continue
                for a, b in zip(old[i1:i2], new[j1:j2], strict=True):
                    ratio = difflib.SequenceMatcher(None, a, b).ratio()
                    if 0.6 <= ratio < 0.98 and b in current_set and a not in current_set:
                        superseded.setdefault((a, b), (old_c, old_d, new_c, new_d))
        for (a, b), (old_c, old_d, new_c, new_d) in superseded.items():
            units.append(
                unit(
                    "site-policy",
                    path,
                    a,
                    f"{path}@{old_c[:10]}",
                    url=f"https://github.com/github/site-policy/blob/{old_c}/{path}",
                    revision=old_c,
                    revision_date=old_d,
                    current=False,
                    superseded_by=unit_id("site-policy", path, b),
                    superseded_at={"revision": new_c, "date": new_d},
                )
            )
    return units


# ---------------------------------------------------------------- KEPs


def section(md: str, title: str) -> str:
    match = re.search(rf"^#+\s*{title}\s*$(.*?)(?=^#+\s)", md, flags=re.M | re.S | re.I)
    return match.group(1) if match else ""


def keps() -> tuple[list[dict], list[dict]]:
    repo = RAW / "k8s-enhancements" / "repo"
    head = git(repo, "rev-parse", "HEAD").strip()
    units, criteria = [], []
    for meta_path in sorted((repo / "keps").glob("*/*/kep.yaml")):
        if "NNNN" in str(meta_path):
            continue
        try:
            # BaseLoader keeps every scalar a string (some KEPs carry invalid dates)
            meta = yaml.load(meta_path.read_text(encoding="utf-8"), Loader=yaml.BaseLoader) or {}
        except yaml.YAMLError:
            continue
        number = meta.get("kep-number")
        title = (meta.get("title") or "").strip()
        if not number or not title:
            continue
        rel = meta_path.parent.relative_to(repo).as_posix()
        url = f"https://github.com/kubernetes/enhancements/tree/{head}/{rel}"
        doc = f"KEP-{number}"
        name = f'KEP-{number} "{title}"'
        facts = [f"{name} is owned by {meta.get('owning-sig')}."]
        if meta.get("status"):
            facts.append(f"The status of {name} is {meta['status']}.")
        if meta.get("stage"):
            facts.append(f"{name} is at the {meta['stage']} stage.")
        if meta.get("latest-milestone"):
            facts.append(f"The latest milestone of {name} is {meta['latest-milestone']}.")
        stones = meta.get("milestone") or {}
        parts = [
            f"{stage} in {stones[stage]}"
            for stage in ("alpha", "beta", "stable")
            if stones.get(stage)
        ]
        if parts:
            facts.append(f"{name} targets " + ", ".join(parts) + ".")
        gates = [
            g.get("name")
            for g in meta.get("feature-gates") or []
            if isinstance(g, dict) and g.get("name")
        ]
        if gates:
            facts.append(f"{name} is controlled by the feature gate(s) {', '.join(gates)}.")
        if meta.get("creation-date"):
            facts.append(f"{name} was created on {meta['creation-date']}.")
        for text in facts:
            units.append(
                unit(
                    "kep",
                    doc,
                    text,
                    f"{rel}/kep.yaml@{head[:10]}",
                    url=url,
                    revision=head,
                    current=True,
                    transformations=["rendered_from_kep_yaml"],
                )
            )
        readme = meta_path.parent / "README.md"
        if not readme.exists():
            continue
        md = readme.read_text(encoding="utf-8", errors="replace")
        for title_re, label in (("Goals", "goal"), ("Non-Goals", "non-goal")):
            for item in clean_markdown(section(md, title_re))[:8]:
                if 25 <= len(item) <= 300:
                    text = f"A {label} of {doc}: {item}"
                    units.append(
                        unit(
                            "kep",
                            doc,
                            text,
                            f"{rel}/README.md#{title_re.lower()}",
                            url=url,
                            revision=head,
                            current=True,
                            transformations=["prefixed_section_label"],
                        )
                    )
        checklist = section(md + "\n# end\n", "Release Signoff Checklist")
        parent = None
        for i, line in enumerate(checklist.splitlines()):
            match = re.match(r"^(\s*)[-*] \[( |x|X)\]\s*(.+)$", line)
            if not match:
                continue
            text = (
                clean_markdown(match.group(3))[0]
                if clean_markdown(match.group(3))
                else match.group(3)
            )
            nested = len(match.group(1)) > 0
            if not nested:
                parent = text
            checked = match.group(2).lower() == "x"
            criteria.append(
                {
                    "record_id": f"crit-kep-{number}-{i:02d}",
                    "task_type": "criterion",
                    "bucket": "public_real",
                    "source_id": "kep",
                    "kep": doc,
                    "kep_title": title,
                    "kep_status": meta.get("status"),
                    "kep_stage": meta.get("stage"),
                    "latest_milestone": meta.get("latest-milestone"),
                    "criterion": text,
                    "required": "(R)" in text,
                    "parent": parent if nested else None,
                    "source_state": "checked" if checked else "unchecked",
                    "label": "MET" if checked else "NOT_MET",
                    "label_tier": "G1",
                    "label_origin": "KEP author's own checkbox (self-assessment)",
                    "url": url,
                    "revision": head,
                    "license": "Apache-2.0",
                    "publishable": True,
                }
            )
    return units, criteria


