def tau() -> tuple[list[dict], list[dict]]:
    repo = RAW / "tau-bench" / "repo"
    head = git(repo, "rev-parse", "HEAD").strip()
    units, runs = [], []
    for domain in ("airline", "retail"):
        rel = f"tau_bench/envs/{domain}/wiki.md"
        policy = (repo / rel).read_text(encoding="utf-8")
        for index, text in enumerate(sentences(policy, low=30)):
            units.append(
                unit(
                    "tau-bench",
                    f"{domain}-policy",
                    text,
                    f"{rel}#s{index}",
                    url=f"https://github.com/sierra-research/tau-bench/blob/{head}/{rel}",
                    revision=head,
                    current=True,
                )
            )
    for path in sorted((repo / "historical_trajectories").glob("*.json")):
        model, domain = path.stem.rsplit("-", 1)
        for run in json.loads(path.read_text(encoding="utf-8")):
            steps = []
            for message in run["traj"]:
                if message.get("role") == "system":
                    continue
                calls = [
                    {"name": c["function"]["name"], "arguments": c["function"].get("arguments")}
                    for c in message.get("tool_calls") or []
                ]
                steps.append(
                    {
                        "role": message.get("role"),
                        "content": message.get("content"),
                        "tool_calls": calls,
                    }
                )
            runs.append(
                {
                    "record_id": f"traj-tau-{path.stem}-{run['task_id']}-{run.get('trial', 0)}",
                    "task_type": "trajectory",
                    "bucket": "public_real",
                    "source_id": "tau-bench",
                    "executor": f"agent:{model}",
                    "step_kind": "dialogue_turn",
                    "domain": domain,
                    "task_id": run["task_id"],
                    "trial": run.get("trial"),
                    "policy_doc": f"{domain}-policy",
                    "steps": steps,
                    "outcome": {"reward": run["reward"], "success": run["reward"] >= 1.0},
                    "label_origin": "tau-bench environment reward (final database state vs goal)",
                    "url": f"https://github.com/sierra-research/tau-bench/blob/{head}/historical_trajectories/{path.name}",
                    "license": "MIT",
                    "publishable": True,
                }
            )
    return units, runs


