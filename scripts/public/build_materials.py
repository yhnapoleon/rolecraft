def jira() -> tuple[list[dict], list[dict]]:
    sources = json.loads((RAW / "jira" / "source.json").read_text(encoding="utf-8"))
    with (RAW / "jira" / "issues.jsonl").open(encoding="utf-8") as handle:
        issues = [json.loads(line) for line in handle]
    browse = {
        "Apache": "https://issues.apache.org/jira/browse/",
        "RedHat": "https://issues.redhat.com/browse/",
        "Jira": "https://jira.atlassian.com/browse/",
        "Mojang": "https://bugs.mojang.com/browse/",
    }
    units, trajectories = [], []
    for issue in issues:
        key = issue["key"]
        url = browse.get(issue["collection"], "") + key
        extra = {"url": url, "revision": sources["page"], "current": True}
        state = (
            f"{key} is a {issue['issuetype']} with {issue['priority'] or 'no'} priority; "
            f"its status is {issue['status']}"
        )
        state += (
            f" and its resolution is {issue['resolution']}." if issue.get("resolution") else "."
        )
        facts = [
            f'{key} in {issue["project"]["name"]} is titled "{issue["summary"].strip()}".',
            state,
        ]
        if issue.get("versions"):
            facts.append(f"{key} affects version(s) {', '.join(issue['versions'])}.")
        created = (issue.get("created") or "")[:10]
        resolved = (issue.get("resolutiondate") or "")[:10]
        if created:
            facts.append(
                f"{key} was created on {created}"
                + (f" and resolved on {resolved}." if resolved else ".")
            )
        if issue.get("duedate"):
            facts.append(f"The due date of {key} is {issue['duedate'][:10]}.")
        for link in issue.get("issuelinks") or []:
            if link.get("key"):
                facts.append(
                    f"{key} has a {link['type']} link ({link['direction']}) to {link['key']}, "
                    f"whose status is {link['status']}."
                )
        for text in facts:
            units.append(unit("jira", key, text, f"{issue['collection']}/{key}", **extra))
        # Fix Version over time: replay the history; each state is a dated version
        states, fix = [], set()
        for history in issue["history"]:
            changed = False
            for item in history["items"]:
                if item["field"] != "Fix Version":
                    continue
                if item["from"]:
                    fix.discard(item["from"])
                if item["to"]:
                    fix.add(item["to"])
                changed = True
            if changed:
                states.append((history["at"], sorted(fix)))
        final = sorted(issue.get("fixVersions") or [])
        if states and states[-1][1] != final:
            states.append((issue.get("updated"), final))
        texts = [
            (
                at,
                f"The fix version of {key} is {', '.join(v)}."
                if v
                else f"{key} has no fix version set.",
            )
            for at, v in states
        ]
        current_text = (
            f"The fix version of {key} is {', '.join(final)}."
            if final
            else f"{key} has no fix version set."
        )
        current_id = unit_id("jira", key, current_text)
        units.append(
            unit("jira", key, current_text, f"{issue['collection']}/{key}#fixVersions", **extra)
        )
        for (at, text), nxt in zip(texts, [*texts[1:], (None, None)], strict=True):
            if text == current_text:
                continue
            units.append(
                unit(
                    "jira",
                    key,
                    text,
                    f"{issue['collection']}/{key}#history@{at}",
                    url=url,
                    revision=sources["page"],
                    current=False,
                    valid_from=at,
                    superseded_by=current_id,
                    superseded_at={"date": nxt[0] or issue.get("updated")},
                )
            )
        moves = sum(
            1
            for h in issue["history"]
            for i in h["items"]
            if i["field"] == "Fix Version" and i["from"]
        )
        days = None
        if created and resolved:
            days = (dt.date.fromisoformat(resolved) - dt.date.fromisoformat(created)).days
        trajectories.append(
            {
                "record_id": f"traj-jira-{key}",
                "task_type": "trajectory",
                "bucket": "public_real",
                "source_id": "jira",
                "executor": "human_team",
                "step_kind": "field_change",
                "collection": issue["collection"],
                "issue": key,
                "project": issue["project"],
                "summary": issue["summary"],
                "steps": [
                    {"seq": n, "at": h["at"], "changes": h["items"]}
                    for n, h in enumerate(issue["history"])
                ],
                "outcome": {
                    "status": issue["status"],
                    "resolution": issue["resolution"],
                    "fix_versions": final,
                    "days_to_resolve": days,
                },
                "features": {"fix_version_moves": moves, "steps": len(issue["history"])},
                "url": url,
                "license": "CC-BY-4.0",
                "publishable": True,
            }
        )
    seen, out = set(), []
    for u in units:
        if u["unit_id"] not in seen:
            seen.add(u["unit_id"])
            out.append(u)
    return out, trajectories


# ---------------------------------------------------------------- TheAgentCompany


def tac() -> tuple[list[dict], list[dict]]:
    repo = RAW / "theagentcompany" / "repo"
    head = git(repo, "rev-parse", "HEAD").strip()
    units, tasks = [], []
    for folder in sorted((repo / "workspaces" / "tasks").glob("pm-*")):
        task_md = (folder / "task.md").read_text(encoding="utf-8")
        checkpoints_md = (folder / "checkpoints.md").read_text(encoding="utf-8")
        checkpoints = [
            {
                "id": int(m.group(1)),
                "points": int(m.group(2)),
                "text": re.sub(r"\s+", " ", m.group(3)).strip(),
            }
            for m in re.finditer(
                r"## Checkpoint (\d+) \((\d+)\s*pts?\)\s*(.*?)(?=## Checkpoint|\Z)",
                checkpoints_md,
                flags=re.S,
            )
        ]
        rel = folder.relative_to(repo).as_posix()
        url = f"https://github.com/TheAgentCompany/TheAgentCompany/tree/{head}/{rel}"
        tasks.append(
            {
                "record_id": f"task-tac-{folder.name}",
                "bucket": "public_real",
                "source_id": "theagentcompany",
                "task": folder.name,
                "task_md": task_md.strip(),
                "checkpoints": checkpoints,
                "total_points": sum(c["points"] for c in checkpoints),
                "url": url,
                "revision": head,
                "license": "MIT",
                "publishable": True,
            }
        )
        for index, text in enumerate(sentences(task_md, low=30)):
            units.append(
                unit(
                    "theagentcompany",
                    folder.name,
                    text,
                    f"{rel}/task.md#s{index}",
                    url=url,
                    revision=head,
                    current=True,
                )
            )
    return units, tasks


