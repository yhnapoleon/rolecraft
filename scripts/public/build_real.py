"""public-real-v1, relation part: three labelled public datasets in the relation-v3 layout.

    uv run --no-project --with scikit-learn --with opencc-python-reimplemented \\
        python -m scripts.public.build_real

Real text, real labels; nothing here is generated by a model.

- ContractNLI (en, CC BY 4.0): every (contract, hypothesis) pair of the official splits.
  Entailment / Contradiction / NotMentioned map to SUPPORTED / CONTRADICTED / INSUFFICIENT;
  the annotated spans are the gold units (first four kept), and the most similar
  non-evidence spans of the same contract (TF-IDF) fill in three hard negatives.
- VitaminC (en, CC BY-SA 3.0): ``revision_type == real`` rows only, i.e. contrastive
  evidence taken from actual Wikipedia revisions; whole ``case_id`` groups are sampled
  from each official split. One candidate per record (the dataset is pair-level).
- CFEVER (zh, Apache-2.0): official train is split 85/15 by claim block into train/dev;
  official dev (balanced, 3,000) becomes test because the official test has no labels.
  Gold units are the first evidence set's sentences; negatives are the most similar other
  sentences of the same pages; NOT ENOUGH INFO claims get the four most similar sentences
  from the pages cited by neighbouring claims. Traditional characters are converted to
  simplified with OpenCC ``t2s``; the original text is kept in ``unit_sources``.
"""

