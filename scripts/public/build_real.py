if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    chosen = set(sys.argv[1:]) or {"contractnli", "vitaminc", "cfever"}
    files = {}
    for name, build in (("contractnli", contractnli), ("vitaminc", vitaminc), ("cfever", cfever)):
        path = OUT / f"relation-{name}.jsonl"
        if name in chosen:
            rows = build()
            write_jsonl(path, rows)
        else:
            rows = [json.loads(line) for line in path.open(encoding="utf-8")]
        files[path.name] = rows
        counts = Counter((r["split"], r["label"]) for r in rows)
        print(name, len(rows), dict(sorted(counts.items())), flush=True)
    for source in ("contractnli", "vitaminc", "cfever"):
        copy_license(OUT, source)
    write_release(
        OUT,
        files,
        {
            "bucket": "public_real",
            "sources": {
                s: {
                    k: source_of(s).get(k)
                    for k in (
                        "page",
                        "url",
                        "repo",
                        "revision",
                        "license",
                        "license_sha256",
                        "retrieved_at",
                        "citation",
                    )
                }
                for s in ("contractnli", "vitaminc", "cfever")
            },
            "labels": {
                name: {
                    f"{k[0]}:{k[1]}": v
                    for k, v in sorted(Counter((r["split"], r["label"]) for r in rows).items())
                }
                for name, rows in files.items()
            },
            "vitaminc_target_rows": VITAMINC_TARGET,
        },
        CARD,
    )
