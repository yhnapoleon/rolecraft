def kb_units(language: str) -> list[dict]:
    from career_lab.recognition.units import split_material
    from career_lab.scenarios.v2.loader import load_package

    index = json.loads(
        (ROOT / "scenarios/pm_pilot/v2/installed/current.json").read_text(encoding="utf-8")
    )
    pkg = load_package(ROOT / index["main"][language]["root"])
    kb = {mid for ids in pkg.bundle.domains.values() for mid in ids}
    domain_of = {mid: d for d, ids in pkg.bundle.domains.items() for mid in ids}
    rows = []
    for m in pkg.materials:
        if m.id not in kb:
            continue
        for f in m.fragments:
            for u in split_material(m.id, m.version, f.text, base=f.ref.span_start or 0):
                if u.kind != "heading" and len(u.text) >= 8:
                    rows.append(
                        {
                            "unit_id": u.unit_id,
                            "material_id": m.id,
                            "version": m.version,
                            "domain": domain_of[m.id],
                            "text": u.text,
                        }
                    )
    return rows


def gen_queries(language: str, units: list[dict], per_unit: int, kind: str) -> list[dict]:
    zh = language == "zh"
    jobs = []
    for unit in units:

        def job(unit=unit):
            if kind == "direct":
                ask = (
                    (
                        f"根据这段知识库原文，写 {per_unit} 个员工会问知识助手的问题，"
                        "答案就在原文里，用词可以接近原文。"
                    )
                    if zh
                    else f"From this knowledge-base passage, write {per_unit} questions an "
                    "employee would "
                    "ask the assistant whose answer is in the passage; wording may stay "
                    "close to it."
                )
            else:
                ask = (
                    f"根据这段知识库原文，写 {per_unit} 个员工会问的问题，答案在原文里，"
                    "但要换说法："
                    "尽量不用原文的关键词，用同义词、口语或举例来问。"
                    if zh
                    else f"From this passage, write {per_unit} questions whose answer is in it, "
                    "but "
                    "rephrase: avoid the passage's key words, use synonyms, casual speech "
                    "or examples."
                )
            found = (
                chat(
                    "Output JSON only.",
                    ask
                    + (
                        '\n输出 {"items": ["..."]}\n原文：'
                        if zh
                        else '\nOutput {"items": ["..."]}\nPassage: '
                    )
                    + unit["text"],
                )
                or {}
            )
            return [
                {
                    "query": q.strip(),
                    "language": language,
                    "kind": "in_" + kind,
                    "answer_unit_id": unit["unit_id"],
                    "material_id": unit["material_id"],
                    "domain": unit["domain"],
                }
                for q in found.get("items", [])
                if isinstance(q, str) and q.strip()
            ]

        jobs.append(job)
    return [row for batch in parallel(jobs) for row in batch]


def gen_out_of_domain(language: str, near: int, far: int) -> list[dict]:
    zh = language == "zh"
    found_near = (
        chat(
            "Output JSON only.",
            (
                "一家公司的内部知识助手只覆盖：常见办公 FAQ、入职、差旅住宿与交通报销、"
                "餐费报销、请假流程。"
                f"写 {near} 个员工可能会问、但不在这些范围内的公司内部问题（例如薪资发放、"
                "体检、晋升、IT 采购、"
                f'团建、股权），要像真的员工提问。输出 {{"items": ["..."]}}'
                if zh
                else "A company's internal assistant covers only: office FAQ, onboarding, "
                "travel hotel and "
                f"transport claims, meal claims and leave. Write {near} realistic employee "
                "questions about "
                "company matters outside that scope (payroll dates, health checks, "
                "promotion, IT purchases, "
                'team events, equity). Output {"items": ["..."]}'
            ),
        )
        or {}
    )
    found_far = (
        chat(
            "Output JSON only.",
            (
                f"写 {far} 个与公司工作完全无关的问题（天气、股票、菜谱、娱乐、编程题、"
                "闲聊等），风格各异。"
                f'输出 {{"items": ["..."]}}'
                if zh
                else f"Write {far} questions unrelated to company work (weather, stocks, recipes, "
                "entertainment, coding puzzles, chit-chat), in varied styles. Output "
                '{"items": ["..."]}'
            ),
        )
        or {}
    )
    rows = [
        {"query": q.strip(), "language": language, "kind": "out_near"}
        for q in found_near.get("items", [])
        if isinstance(q, str) and q.strip()
    ]
    rows += [
        {"query": q.strip(), "language": language, "kind": "out_far"}
        for q in found_far.get("items", [])
        if isinstance(q, str) and q.strip()
    ]
    return rows


def check_answerable(rows: list[dict], units: list[dict], k: int = 5) -> list[dict]:
    """Program check: an in-domain query's source unit must be in the C2 top-k."""
    from career_lab.recognition import retrieval

    texts = [u["text"] for u in units]
    index = {u["unit_id"]: i for i, u in enumerate(units)}
    for r in rows:
        if not r["kind"].startswith("in_"):
            r["answerable"] = None
            continue
        hits, _, _ = retrieval.search(r["query"], texts, k=k, method="rrf")
        r["answer_rank"] = next(
            (h.rank for h in hits if h.index == index.get(r["answer_unit_id"])), None
        )
        r["answerable"] = r["answer_rank"] is not None
    return rows


def cmd_queries(args) -> None:
    rows = []
    for language in ("zh", "en"):
        units = kb_units(language)
        rng = random.Random(3 if language == "zh" else 4)
        pick = rng.sample(units, min(len(units), args.units))
        found = gen_queries(language, pick, args.per_unit, "direct")
        found += gen_queries(language, pick, args.per_unit, "paraphrase")
        found += gen_out_of_domain(language, args.near, args.far)
        rows += check_answerable(found, units)
    kept = [r for r in rows if r["answerable"] is not False]
    split(kept, key_of=lambda r: r.get("answer_unit_id") or r["query"])
    write_release(
        Path(args.out),
        {"queries.jsonl": kept, "rejected.jsonl": [r for r in rows if r["answerable"] is False]},
        {"units": args.units, "per_unit": args.per_unit, "near": args.near, "far": args.far},
        f"""# assistant-queries-v1

Questions to the knowledge assistant: in-domain direct (`in_direct`), in-domain paraphrased
(`in_paraphrase`), near out-of-domain company questions (`out_near`) and far out-of-domain
questions (`out_far`), Chinese and English. In-domain questions carry their source unit;
an in-domain question is kept only when that unit is in the C2 (BM25+e5 RRF) top-5.
Split 60/20/20 grouped by source unit. Use: C4 scope detection evaluation (E5) and C2 (E3).
Kept {len(kept)} of {len(rows)}.
""",
    )
    print("queries kept", len(kept), "of", len(rows), USAGE)


def cmd_paraphrases(args) -> None:
    rows = []
    for language in ("zh", "en"):
        units = kb_units(language)
        rng = random.Random(5 if language == "zh" else 6)
        pick = rng.sample(units, min(len(units), args.units))
        found = gen_queries(language, pick, args.per_unit, "paraphrase")
        rows += check_answerable(found, units)
    kept = [r for r in rows if r["answerable"]]
    write_release(
        Path(args.out),
        {"paraphrases.jsonl": kept},
        {"units": args.units, "per_unit": args.per_unit},
        f"""# paraphrases-v1

Paraphrased in-domain questions used only to fit the C4 in-domain distribution (all train),
generated from different units/seeds than assistant-queries-v1. Kept {len(kept)} of {len(rows)}.
""",
    )
    print("paraphrases kept", len(kept), "of", len(rows), USAGE)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("intent")
    p.add_argument("--out", required=True)
    p.add_argument("--per-cell", type=int, default=34)
    p = sub.add_parser("queries")
    p.add_argument("--out", required=True)
    p.add_argument("--units", type=int, default=25)
    p.add_argument("--per-unit", type=int, default=4)
    p.add_argument("--near", type=int, default=50)
    p.add_argument("--far", type=int, default=50)
    p = sub.add_parser("paraphrases")
    p.add_argument("--out", required=True)
    p.add_argument("--units", type=int, default=34)
    p.add_argument("--per-unit", type=int, default=3)
    p = sub.add_parser("relation")
    p.add_argument("--out", required=True)
    p.add_argument("--per-unit", type=int, default=6)
    p.add_argument("--units", type=int, default=340)
    p.add_argument("--rounds", type=int, default=2)
    args = parser.parse_args(argv)
    if args.command == "relation":
        from scripts.recognition.synth_relation import cmd_relation

        cmd_relation(args)
    else:
        {"intent": cmd_intent, "queries": cmd_queries, "paraphrases": cmd_paraphrases}[
            args.command
        ](args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
