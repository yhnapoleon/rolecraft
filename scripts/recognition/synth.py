# ---- intent ------------------------------------------------------------------------------

INTENTS = {
    "ask_limit": (
        "询问限制、上限、约束、容量（问“最多/上限/能不能超过”）",
        "asks about limits, caps, constraints or capacity",
    ),
    "ask_resource": (
        "询问资源、人力、天数、预算、工作量",
        "asks about resources, people, days, budget or effort",
    ),
    "ask_process": (
        "询问流程、步骤、怎么做、下一步",
        "asks how to do something, the process, steps or next step",
    ),
    "seek_approval": (
        "请求对方批准、同意、放行、签字",
        "asks the colleague to approve, agree, grant or sign off",
    ),
    "other": (
        "闲聊、表达情绪、确认收到、与工作无关或以上都不是",
        "small talk, feelings, acknowledgements, off-topic, or none of the above",
    ),
}
STYLES = {
    "formal": ("正式书面", "formal written"),
    "casual": ("口语随意", "casual spoken"),
    "terse": ("极简短（不超过 10 个字）", "very terse (under 8 words)"),
    "contextual": ("先交代一点背景再提问", "gives a little context before the question"),
}


def gen_intent(language: str, per_cell: int) -> list[dict]:
    zh = language == "zh"
    jobs = []
    for intent, (dz, de) in INTENTS.items():
        for style, (sz, se) in STYLES.items():

            def job(intent=intent, style=style, dz=dz, de=de, sz=sz, se=se):
                system = SCENARIO[language] + (
                    "\n你在为意图识别器造训练数据。只输出 JSON。"
                    if zh
                    else "\nYou write training data for an intent recognizer. Output JSON only."
                )
                user = (
                    f"写 {per_cell} 句学员对同事说的话，意图是：{dz}；文风：{sz}。彼此要有差异，"
                    f'不要都用同一个关键词。输出 {{"items": ["..."]}}。'
                    if zh
                    else f"Write {per_cell} things the learner says to a colleague. Intent: {de}. "
                    f"Style: {se}. Vary them; do not reuse one keyword. "
                    'Output {"items": ["..."]}.'
                )
                found = chat(system, user) or {}
                return [
                    {"text": t.strip(), "intent": intent, "style": style, "language": language}
                    for t in found.get("items", [])
                    if isinstance(t, str) and t.strip()
                ]

            jobs.append(job)
    rows = [row for batch in parallel(jobs) for row in batch]
    return review_intent(rows, language)


def review_intent(rows: list[dict], language: str) -> list[dict]:
    zh = language == "zh"
    labels = ", ".join(INTENTS)
    guide = "; ".join(f"{k}: {v[0] if zh else v[1]}" for k, v in INTENTS.items())
    random.Random(11).shuffle(rows)
    chunks = [rows[i : i + 40] for i in range(0, len(rows), 40)]

    def job(chunk):
        def run():
            numbered = {str(i): r["text"] for i, r in enumerate(chunk)}
            found = (
                chat(
                    SCENARIO[language]
                    + (
                        "\n你是标注员，只输出 JSON。"
                        if zh
                        else "\nYou are an annotator. Output JSON only."
                    ),
                    (
                        f"给每句话标一个意图（{labels}）。定义：{guide}。"
                        f'输出 {{"labels": {{"编号": "意图"}}}}。\n'
                        if zh
                        else f"Label each utterance with one intent ({labels}). Definitions: "
                        f"{guide}. "
                        'Output {"labels": {"id": "intent"}}.\n'
                    )
                    + json.dumps(numbered, ensure_ascii=False),
                    temperature=0.0,
                )
                or {}
            )
            got = found.get("labels", {})
            return [r | {"review": got.get(str(i))} for i, r in enumerate(chunk)]

        return run

    reviewed = [r for batch in parallel([job(c) for c in chunks]) for r in batch]
    return reviewed


def cmd_intent(args) -> None:
    rows = []
    for language in ("zh", "en"):
        rows += gen_intent(language, args.per_cell)
    seen, kept = set(), []
    for r in rows:
        norm = re.sub(r"\s+", "", r["text"].casefold())
        if norm in seen:
            continue
        seen.add(norm)
        r["agreed"] = r["review"] == r["intent"]
        kept.append(r)
    agreed = [r for r in kept if r["agreed"]]
    split(agreed, key_of=lambda r: r["text"])
    write_release(
        Path(args.out),
        {"intent.jsonl": agreed, "rejected.jsonl": [r for r in kept if not r["agreed"]]},
        {"intents": list(INTENTS), "styles": list(STYLES), "per_cell": args.per_cell},
        f"""# intent-v1

Learner utterances to colleagues, five intents x four styles, Chinese and English.
Generated by DeepSeek ({MODEL}); a second, label-blind pass re-labelled every item and only
agreeing items are kept (`intent.jsonl`; disagreements in `rejected.jsonl`).
Split 60/20/20 by utterance. Kept {len(agreed)} of {len(kept)} unique items.
Use: C11 intent recognizer (TF-IDF char 2-4 gram + logistic regression).
""",
    )
    print("intent kept", len(agreed), "of", len(kept), USAGE)


