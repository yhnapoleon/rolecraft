"""DeepSeek synthesis with a blind second pass, for the recognition-layer datasets.

    python -m scripts.recognition.synth intent      --out data/releases/intent-v1
    python -m scripts.recognition.synth queries     --out data/releases/assistant-queries-v1
    python -m scripts.recognition.synth paraphrases --out data/releases/paraphrases-v1
    python -m scripts.recognition.synth relation    --out data/releases/relation-v3 --per-unit 6

Every family is generated by one prompt per cell of its generation matrix, then a second
call that sees only the items (never the requested labels) re-labels them; an item is kept
only when both passes agree (queries and paraphrases are checked by program instead:
the source unit must be retrievable). Outputs are JSONL files plus ``manifest.json``,
``data_card.md`` and ``SHA256SUMS`` (UTF-8, ``\\n`` line endings). The key is read from
``ds.txt`` at the repository root and never written anywhere.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[2]
MODEL = "deepseek-chat"
BASE = "https://api.deepseek.com"
_LOCK = threading.Lock()
USAGE = {"calls": 0, "prompt_tokens": 0, "completion_tokens": 0}


def key() -> str:
    for line in (ROOT / "ds.txt").read_text(encoding="utf-8-sig").splitlines():
        if line.strip() and not line.startswith("#"):
            return line.strip()
    raise SystemExit("ds.txt has no key")


def chat(system: str, user: str, *, temperature: float = 0.9, retries: int = 4) -> Any:
    """One JSON-mode DeepSeek call; returns the parsed JSON object."""
    for attempt in range(retries):
        try:
            response = httpx.post(
                BASE + "/chat/completions",
                headers={"Authorization": "Bearer " + key()},
                json={
                    "model": MODEL,
                    "messages": [
                        {"role": "system", "content": system},
                        {"role": "user", "content": user},
                    ],
                    "temperature": temperature,
                    "response_format": {"type": "json_object"},
                    "max_tokens": 6000,
                },
                timeout=180,
                trust_env=False,
            )
            response.raise_for_status()
            body = response.json()
            with _LOCK:
                USAGE["calls"] += 1
                for k in ("prompt_tokens", "completion_tokens"):
                    USAGE[k] += body.get("usage", {}).get(k, 0)
            return json.loads(body["choices"][0]["message"]["content"])
        except Exception as error:  # noqa: BLE001 - retry transient failures
            if attempt == retries - 1:
                print("call failed:", type(error).__name__, str(error)[:200], flush=True)
                return None
            time.sleep(2 + 3 * attempt)
    return None


def parallel(jobs, workers: int = 6):
    with ThreadPoolExecutor(workers) as pool:
        return list(pool.map(lambda job: job(), jobs))


def write_release(out: Path, files: dict[str, list[dict]], spec: dict, card: str) -> None:
    out.mkdir(parents=True, exist_ok=True)
    sums = []
    for name, rows in files.items():
        path = out / name
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            for row in rows:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        sums.append((name, hashlib.sha256(path.read_bytes()).hexdigest(), len(rows)))
    manifest = {
        "schema_version": 1,
        "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "generator": {"provider": "deepseek", "model": MODEL},
        "spec": spec,
        "files": [{"path": n, "sha256": h, "records": c} for n, h, c in sums],
        "usage": dict(USAGE),
    }
    with (out / "manifest.json").open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    with (out / "data_card.md").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(card.strip() + "\n")
    lines = []
    for name in sorted([*files, "manifest.json", "data_card.md"]):
        lines.append(f"{hashlib.sha256((out / name).read_bytes()).hexdigest()}  {name}\n")
    with (out / "SHA256SUMS").open("w", encoding="utf-8", newline="\n") as handle:
        handle.writelines(lines)


def split(rows: list[dict], key_of, seed: int = 7, ratios=(0.6, 0.2, 0.2)) -> list[dict]:
    """Group-aware 60/20/20 split: every group lands in exactly one partition."""
    groups = sorted({key_of(r) for r in rows})
    random.Random(seed).shuffle(groups)
    cut1, cut2 = int(len(groups) * ratios[0]), int(len(groups) * (ratios[0] + ratios[1]))
    part = {
        g: ("train" if i < cut1 else "dev" if i < cut2 else "test") for i, g in enumerate(groups)
    }
    for r in rows:
        r["split"] = part[key_of(r)]
    return rows


