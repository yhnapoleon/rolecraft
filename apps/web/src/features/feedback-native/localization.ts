export const feedbackCopy = (
  language: FeedbackLanguage,
  key: FeedbackCopyKey,
  values?: Readonly<Record<string, string | number>>,
) => copyText(FEEDBACK_COPY, language, key, values);
/** A counted phrase: the `…One` entry when there is exactly one (English needs it). */
export const feedbackCount = (
  language: FeedbackLanguage,
  key: FeedbackCopyKey,
  n: number,
  values: Readonly<Record<string, string | number>> = {},
) => {
  const one = `${key}One` as FeedbackCopyKey;
  return feedbackCopy(language, n === 1 && one in FEEDBACK_COPY[language] ? one : key, {
    n,
    ...values,
  });
};
