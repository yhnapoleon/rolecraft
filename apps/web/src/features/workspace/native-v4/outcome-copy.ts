export const outcomeTables = { zh, en, zhTerms, enTerms };

export function outcomeText(
  language: OutcomeLanguage,
  key: OutcomeKey,
  values: Record<string, string | number> = {},
): string {
  const template = (language === 'en' ? en : zh)[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}

export function outcomeTerm(language: OutcomeLanguage, group: string, code: string): string {
  const key = `${group}_${code}` as TermKey;
  return (language === 'en' ? enTerms : zhTerms)[key] ?? code;
}
